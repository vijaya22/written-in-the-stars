// Letter skeletons for matching against stars. Each glyph is a handful of
// vertices (which must each land on a star) plus the strokes drawn between them.
// Coordinates: y up, baseline at 0, cap height 1. Curves are coarse polygons,
// on purpose: every extra vertex is one more star that has to line up.

export interface Glyph {
  pts: [number, number][];
  edges: [number, number][];
}

const chain = (n: number, closed = false): [number, number][] => {
  const e: [number, number][] = [];
  for (let i = 0; i < n - 1; i++) e.push([i, i + 1]);
  if (closed) e.push([n - 1, 0]);
  return e;
};

